<?php

/**
 * @file
 * Builds CSpell configs the way the drupal.org GitLab CI "cspell" job does.
 *
 * Usage:
 *   php cspell.php project <project-dir> <output-file>
 *     Writes the expanded config CI would use for one project.
 *   php cspell.php vscode <output-file> [<project-dir> ...]
 *     Writes a site-wide config for the VSCode extension: the CI defaults for
 *     all files, plus one "overrides" entry per project with the project's
 *     expanded settings (words, project dictionary, ignore paths, ...).
 *
 * CI copies the project's .cspell.json (or the gitlab_templates default) and
 * runs gitlab_templates' prepare-cspell.php on it from the project root. This
 * script runs the vendored, unmodified prepare-cspell.php the same way, but
 * reads and writes temporary files, so nothing is written into the project.
 */

const GLOBAL_DICTIONARIES = ['drupal', 'dictionary'];

$ciDir = dirname(__DIR__);
$appRoot = getenv('DDEV_COMPOSER_ROOT') ?: '/var/www/html';
$webRoot = $appRoot . '/' . (getenv('DDEV_DOCROOT') ?: 'web');

$mode = $argv[1] ?? '';
if ($mode === 'project' && count($argv) === 4) {
  writeJson($argv[3], prepareProject(realpath($argv[2])));
}
elseif ($mode === 'vscode' && count($argv) >= 3) {
  writeJson($argv[2], buildVscodeConfig(array_map('realpath', array_slice($argv, 3))));
}
else {
  fwrite(STDERR, "Usage: php cspell.php project <project-dir> <output-file>\n       php cspell.php vscode <output-file> [<project-dir> ...]\n");
  exit(2);
}

/**
 * Returns the config CI would use for a project, with absolute paths.
 */
function prepareProject(string $project): array {
  global $ciDir, $webRoot;

  $input = is_file("$project/.cspell.json") ? "$project/.cspell.json" : "$ciDir/assets/.cspell.json";
  $tmpIn = tempnam(sys_get_temp_dir(), 'cspell-in-');
  $tmpOut = tempnam(sys_get_temp_dir(), 'cspell-out-');
  $tmpScript = tempnam(sys_get_temp_dir(), 'prepare-cspell-');
  copy($input, $tmpIn);

  // Let prepare-cspell.php read and write the temporary files instead of
  // .cspell.json in the working directory.
  $source = file_get_contents("$ciDir/scripts/prepare-cspell.php");
  $source = str_replace("\$cspell_filename = '.cspell.json';", "\$cspell_filename = getenv('DRUPAL_CI_CSPELL_IN');", $source, $countIn);
  $source = str_replace("\$cspell_filename .= \$suffix;", "\$cspell_filename = getenv('DRUPAL_CI_CSPELL_OUT');", $source, $countOut);
  if ($countIn !== 1 || $countOut !== 1) {
    fail('The vendored prepare-cspell.php changed, adjust ' . __FILE__ . '.');
  }
  file_put_contents($tmpScript, $source);

  // The CI variables with their gitlab_templates default values.
  $env = [
    'DRUPAL_CI_CSPELL_IN' => $tmpIn,
    'DRUPAL_CI_CSPELL_OUT' => $tmpOut,
    'CI_PROJECT_NAME' => basename($project),
    '_WEB_ROOT' => $webRoot,
    '_CSPELL_DICTIONARY' => '.cspell-project-words.txt',
    '_CSPELL_MINWORDLENGTH' => '4',
    '_CSPELL_IGNORE_STANDARD_FILES' => '1',
  ];
  $process = proc_open([PHP_BINARY, $tmpScript], [1 => ['pipe', 'w']], $pipes, $project, $env + getenv());
  $output = stream_get_contents($pipes[1]);
  fclose($pipes[1]);
  $exitCode = proc_close($process);
  // Forward warnings (e.g. missing default flag words), but not the noise.
  foreach (explode("\n", trim($output)) as $line) {
    if ($line !== '' && !str_starts_with($line, 'Writing json array')) {
      fwrite(STDERR, $line . "\n");
    }
  }
  $config = json_decode((string) file_get_contents($tmpOut), TRUE);
  @unlink($tmpIn);
  @unlink($tmpOut);
  @unlink($tmpScript);
  if ($exitCode !== 0 || !is_array($config)) {
    fail("prepare-cspell.php failed for $project.");
  }

  // The config is used from outside the project, so make its paths absolute.
  $config['globRoot'] = $project;
  foreach ($config['dictionaryDefinitions'] ?? [] as $key => $definition) {
    $config['dictionaryDefinitions'][$key]['path'] = absolutePath($definition['path'], $project);
  }
  if (!empty($config['import'])) {
    $config['import'] = array_map(fn ($path) => absolutePath($path, $project), (array) $config['import']);
  }
  // The web root is ignored in CI because Drupal is installed inside the
  // project there. Here it is the absolute path of the site's web root.
  $config['ignorePaths'] = array_values(array_diff($config['ignorePaths'] ?? [], [$webRoot]));
  return $config;
}

/**
 * Returns the site-wide config for the VSCode extension.
 */
function buildVscodeConfig(array $projects): array {
  global $ciDir, $appRoot;

  // The defaults, from an empty project.
  $emptyProject = sys_get_temp_dir() . '/drupal-ci-cspell-' . getmypid();
  mkdir($emptyProject);
  $defaults = prepareProject($emptyProject);
  rmdir($emptyProject);

  $config = [
    'description' => 'Generated by "ddev drupal-ci-setup" (.ddev/drupal-ci), do not edit. Mirrors the drupal.org GitLab CI cspell job: CI defaults for all files, plus one "overrides" entry per project.',
    'version' => '0.2',
    'language' => $defaults['language'] ?? 'en-US',
    'allowCompoundWords' => $defaults['allowCompoundWords'] ?? FALSE,
    'globRoot' => '.',
    'minWordLength' => $defaults['minWordLength'] ?? 4,
    'ignorePaths' => [
      '.ddev',
      '.git',
      '.vscode',
      'data',
      'files',
      'node_modules',
      'repos',
      'tmp',
      'vendor',
      'web/core',
      'web/libraries',
      'web/modules/contrib',
      'web/profiles/contrib',
      'web/sites',
      'web/themes/contrib',
      'web/.*',
      'web/*.*',
      '**/node_modules',
      '**/vendor',
      '*.patch',
      '*.svg',
      '*cspell.json',
      '**/.*.json',
      '.*ignore',
      'composer.json',
      'composer.lock',
      'package.json',
      'package-lock.json',
      'yarn.lock',
      'phpstan*',
      'phpunit.xml',
    ],
    'dictionaries' => [],
    'dictionaryDefinitions' => [],
    'flagWords' => $defaults['flagWords'] ?? [],
    'overrides' => $defaults['overrides'] ?? [],
  ];
  foreach ($defaults['dictionaryDefinitions'] ?? [] as $definition) {
    if (in_array($definition['name'], GLOBAL_DICTIONARIES, TRUE)) {
      $definition['path'] = relativePath($definition['path'], $appRoot);
      $config['dictionaryDefinitions'][] = $definition;
    }
  }
  $config['dictionaries'] = $defaults['dictionaries'] ?? [];

  $excludedKeys = [
    'version', '$schema', 'description', 'language', 'globRoot', 'ignorePaths',
    'dictionaryDefinitions', 'overrides', 'import', 'files', 'name', 'id',
  ];
  foreach ($projects as $project) {
    $prepared = prepareProject($project);
    $relative = relativePath($project, $appRoot);

    // Project dictionaries get unique names, since all share one config.
    $renamed = [];
    foreach ($prepared['dictionaryDefinitions'] ?? [] as $definition) {
      if (in_array($definition['name'], GLOBAL_DICTIONARIES, TRUE)) {
        continue;
      }
      $renamed[$definition['name']] = $definition['name'] . '--' . str_replace('/', '--', $relative);
      $definition['name'] = $renamed[$definition['name']];
      $definition['path'] = relativePath($definition['path'], $appRoot);
      $config['dictionaryDefinitions'][] = $definition;
    }

    $override = ['filename' => "$relative/**"];
    foreach ($prepared as $key => $value) {
      if (!in_array($key, $excludedKeys, TRUE)) {
        $override[$key] = $value;
      }
    }
    $override['dictionaries'] = array_map(fn ($name) => $renamed[$name] ?? $name, $prepared['dictionaries'] ?? []);
    $config['overrides'][] = $override;

    foreach ($prepared['ignorePaths'] ?? [] as $pattern) {
      $pattern = preg_replace('#^\./#', '', $pattern);
      if (str_starts_with($pattern, '/')) {
        $config['ignorePaths'][] = $relative . $pattern;
      }
      elseif (!str_contains($pattern, '/')) {
        $config['ignorePaths'][] = "$relative/**/$pattern";
      }
      else {
        $config['ignorePaths'][] = "$relative/$pattern";
      }
    }
  }
  $config['ignorePaths'] = array_values(array_unique($config['ignorePaths']));
  return $config;
}

function absolutePath(string $path, string $base): string {
  if (str_starts_with($path, '/')) {
    return $path;
  }
  return $base . '/' . preg_replace('#^\./#', '', $path);
}

function relativePath(string $path, string $base): string {
  return str_starts_with($path, "$base/") ? substr($path, strlen($base) + 1) : $path;
}

function writeJson(string $file, array $data): void {
  file_put_contents($file, json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n");
}

function fail(string $message): never {
  fwrite(STDERR, "drupal-ci: $message\n");
  exit(2);
}
